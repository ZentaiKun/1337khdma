int	ft_isalnum(int c)
{
	int	alphanum;

	alphanum = 1;
	if ((c < '0' || c > '9') && (c < 'a' || c > 'z') && (c < 'A' || c > 'Z'))
		alphanum = 0;
	return (alphanum);
}
